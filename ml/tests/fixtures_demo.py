def _fsp(kind: str = "prize", discipline: str = "Продуктовое программирование") -> MatcherFspAchievement:
    return MatcherFspAchievement(
        id=f"fsp-{kind}-{discipline[:8]}",
        title="Соревнование ФСП",
        discipline=discipline,
        place_or_result="2 место" if kind == "prize" else "участник",
        sport_rank="1 разряд" if kind == "prize" else None,
        verified=True,
        achievement_type=kind,
    )


