"""Demo question bank: (specialization slug, grade code) -> questions.

Topics follow `services.testing.BLUEPRINTS`. Correct answers are spread over a-d and the
options are reshuffled for every attempt, so "always pick b" does not pass the test.
"""

from __future__ import annotations

from dataclasses import dataclass

OPTION_IDS = ("a", "b", "c", "d")


@dataclass(frozen=True)
class SeedQuestion:
    topic: str
    prompt: str
    options: tuple[str, str, str, str]
    correct: str  # one of OPTION_IDS

    def options_json(self) -> list[dict[str, str]]:
        return [
            {"id": oid, "text": text} for oid, text in zip(OPTION_IDS, self.options, strict=True)
        ]


def q(topic: str, prompt: str, options: tuple[str, str, str, str], correct: str) -> SeedQuestion:
    return SeedQuestion(topic, prompt, options, correct)


